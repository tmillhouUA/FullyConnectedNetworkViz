// Builds mnist14.js: a class-balanced subset of MNIST, shrunk to 14x14, for
// the visualization to load with a plain <script> tag (which, unlike fetch(),
// works when index.html is opened straight from disk).
//
// Run once with Node (no packages needed), from the project folder:
//   node tools/build-data.js [cacheDir]
// The original MNIST files are downloaded into cacheDir (default: a folder
// in the system temp directory) and reused on later runs.
//
// Output format (see the header written into mnist14.js):
//   images: every image's 196 pixels, one byte each (0 = background,
//           255 = ink), concatenated, gzipped, then base64-encoded.
//   labels: one digit character per image, in the same order.

const fs   = require("fs");
const os   = require("os");
const path = require("path");
const zlib = require("zlib");

// ---------- Settings ----------
const TRAIN_PER_CLASS = 1000;  // 10 classes -> 10,000 training images
const TEST_PER_CLASS  = 200;   // 10 classes -> 2,000 test images
const SRC_SIZE = 28;           // MNIST images are 28x28
const OUT_SIZE = 14;           // shrink by averaging each 2x2 block
const OUT_FILE = path.join(__dirname, "..", "mnist14.js");

// Mirror of the original MNIST files (the one PyTorch uses; the original
// yann.lecun.com host is often unavailable).
const MIRROR = "https://ossci-datasets.s3.amazonaws.com/mnist/";
const FILES = {
  trainImages: "train-images-idx3-ubyte.gz",
  trainLabels: "train-labels-idx1-ubyte.gz",
  testImages:  "t10k-images-idx3-ubyte.gz",
  testLabels:  "t10k-labels-idx1-ubyte.gz",
};

const cacheDir = process.argv[2] || path.join(os.tmpdir(), "mnist-raw");

// ---------- Download (or reuse) and unzip one MNIST file ----------
async function loadFile(name) {
  const cached = path.join(cacheDir, name);
  if (!fs.existsSync(cached)) {
    console.log(`Downloading ${name} ...`);
    const response = await fetch(MIRROR + name);
    if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
    fs.mkdirSync(cacheDir, { recursive: true });
    fs.writeFileSync(cached, Buffer.from(await response.arrayBuffer()));
  }
  return zlib.gunzipSync(fs.readFileSync(cached));
}

// ---------- Parse MNIST's "IDX" format ----------
// Images: 4-byte magic number 2051, count, rows, cols (big-endian), then
// one byte per pixel. Labels: magic 2049, count, then one byte per label.
function parseImages(buf) {
  if (buf.readUInt32BE(0) !== 2051) throw new Error("not an IDX image file");
  const count = buf.readUInt32BE(4);
  const rows  = buf.readUInt32BE(8);
  const cols  = buf.readUInt32BE(12);
  if (rows !== SRC_SIZE || cols !== SRC_SIZE) throw new Error("unexpected image size");
  return { count, pixels: buf.subarray(16) };
}

function parseLabels(buf) {
  if (buf.readUInt32BE(0) !== 2049) throw new Error("not an IDX label file");
  return buf.subarray(8, 8 + buf.readUInt32BE(4));
}

// ---------- Shrink one 28x28 image to 14x14 ----------
// Each output pixel is the rounded average of a 2x2 block of input pixels.
function shrink(pixels, index) {
  const src = index * SRC_SIZE * SRC_SIZE;
  const out = new Uint8Array(OUT_SIZE * OUT_SIZE);
  for (let r = 0; r < OUT_SIZE; r++) {
    for (let c = 0; c < OUT_SIZE; c++) {
      const top = src + (2 * r) * SRC_SIZE + 2 * c;
      const sum = pixels[top] + pixels[top + 1] +
                  pixels[top + SRC_SIZE] + pixels[top + SRC_SIZE + 1];
      out[r * OUT_SIZE + c] = Math.round(sum / 4);
    }
  }
  return out;
}

// ---------- Pick a class-balanced subset ----------
// Takes the first perClass images of each digit, keeping MNIST's original
// order (in which the digits are already mixed together).
function buildSubset(images, labels, perClass) {
  const taken = new Array(10).fill(0);
  const chosen = [];
  for (let i = 0; i < images.count && chosen.length < 10 * perClass; i++) {
    const d = labels[i];
    if (taken[d] < perClass) {
      taken[d]++;
      chosen.push(i);
    }
  }
  const out = new Uint8Array(chosen.length * OUT_SIZE * OUT_SIZE);
  chosen.forEach((i, k) => out.set(shrink(images.pixels, i), k * OUT_SIZE * OUT_SIZE));
  return {
    count:  chosen.length,
    labels: chosen.map(i => labels[i]).join(""),
    images: zlib.gzipSync(out, { level: 9 }).toString("base64"),
  };
}

// ---------- Main ----------
async function main() {
  const train = buildSubset(
    parseImages(await loadFile(FILES.trainImages)),
    parseLabels(await loadFile(FILES.trainLabels)),
    TRAIN_PER_CLASS);
  const test = buildSubset(
    parseImages(await loadFile(FILES.testImages)),
    parseLabels(await loadFile(FILES.testLabels)),
    TEST_PER_CLASS);

  const js =
`// MNIST, shrunk to 14x14 (each pixel the average of a 2x2 block) and
// subset to ${TRAIN_PER_CLASS} training / ${TEST_PER_CLASS} test images per digit.
// Generated by tools/build-data.js -- do not edit by hand.
//
// images: ${OUT_SIZE * OUT_SIZE} bytes per image (row-major; 0 = background, 255 = ink),
//         all images concatenated, gzipped, then base64-encoded.
// labels: one digit character per image, in the same order.
//
// MNIST is by Yann LeCun, Corinna Cortes and Christopher J.C. Burges.
window.MNIST14 = {
  rows: ${OUT_SIZE},
  cols: ${OUT_SIZE},
  train: {
    count: ${train.count},
    labels: "${train.labels}",
    images: "${train.images}",
  },
  test: {
    count: ${test.count},
    labels: "${test.labels}",
    images: "${test.images}",
  },
};
`;
  fs.writeFileSync(OUT_FILE, js);
  console.log(`Wrote ${OUT_FILE}: ${train.count} train, ${test.count} test, ` +
              `${(js.length / 1024).toFixed(0)} KB`);
}

main().catch(err => { console.error(err); process.exit(1); });
